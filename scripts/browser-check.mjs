import assert from 'node:assert/strict';
import {mkdir,readFile} from 'node:fs/promises';
import {chromium} from 'playwright';
import {createApp} from '../bridge/server.js';
const app=createApp();
let clock=Date.now();
app.world.now=()=>clock;
await new Promise(resolve=>app.server.listen(0,'127.0.0.1',resolve));
const origin='http://127.0.0.1:'+app.server.address().port;
let browser;
try {
 browser=await chromium.launch({executablePath:process.env.XOM_TEST_CHROMIUM,args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--autoplay-policy=no-user-gesture-required']});
 const context=await browser.newContext({viewport:{width:540,height:960}});
 const page=await context.newPage();
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(origin+'/admin');
 await page.click('#demo-mode');
 const game=await context.newPage();
 game.on('pageerror',e=>errors.push(e.message));
 await game.goto(origin+'/');
 await game.waitForFunction(()=>window.__office?.state?.office);
 await game.waitForFunction(()=>[...document.images].every(img=>img.complete&&img.naturalWidth>0));
 assert.equal(await game.locator('.gift').count(),9);
 await game.click('#audio-start');
 await mkdir('artifacts',{recursive:true});
 await game.screenshot({path:'artifacts/office-idle.png'});
 const trigger=async gift=>{
  const response=await page.request.post(origin+'/api/demo',{headers:{Origin:origin},data:{type:'gift',giftName:gift,name:'Khách kiểm thử',viewer:1,count:1}});
  assert.ok(response.ok());
 };
 const skip=async()=>{
  assert.ok((await page.request.post(origin+'/api/office-skip',{headers:{Origin:origin},data:{}})).ok());
  await game.waitForFunction(()=>!__office.state.office.active);
 };
 await trigger('Okay');
 await game.waitForFunction(()=>__office.state.office.active?.key==='claimCeo');
 assert.equal(await game.locator('#ceo-name').textContent(),'@Khách kiểm thử');
 clock=app.world.office.active.started+2000;
 await game.waitForFunction(()=>!document.querySelector('#subtitle').hidden);
 await game.waitForFunction(()=>__office.audio.voice.currentTime>.1);
 assert.equal(await game.evaluate(()=>__office.audio.voice.paused),false);
 await game.screenshot({path:'artifacts/office-speaking.png'});
 await skip();
 for(const [gift,key] of [['Rose','kiss'],['Bouquet Flower','wedding'],['Bravo!','lieu']]){
  await trigger(gift);
  await game.waitForFunction(key=>__office.state.office.active?.key===key,key);
  clock=app.world.office.active.started+1000;
  await game.waitForFunction(key=>document.querySelector('#camera').className==='scene-'+key,key);
  if(key==='lieu'){
    clock=app.world.office.active.started+3000;
    await game.waitForFunction(()=>Number(document.getElementById('lieu').style.opacity)===1);
    assert.equal(await game.locator('#lieu-name').textContent(),'@Khách kiểm thử');
  }
  await game.screenshot({path:'artifacts/office-'+key+'.png'});
  await skip();
 }
 await trigger('Doughnut');
 await game.waitForFunction(()=>__office.state.office.active?.key==='bedroom');
 await trigger('Shamrock');
 await game.waitForFunction(()=>__office.state.office.active?.key==='replaceCeo');
 assert.equal(app.world.office.recent[0].interrupted,true);
 await skip();
 await trigger('Paper Crane');await game.waitForFunction(()=>__office.state.office.active?.key==='fire');
 clock=app.world.office.active.end+1;
 await game.waitForFunction(()=>!__office.state.office.secretary.present);
 assert.equal(await game.locator('#secretary').evaluate(el=>getComputedStyle(el).visibility),'hidden');
 await trigger('Lucky Pig');await game.waitForFunction(()=>__office.state.office.secretary.present);
 await skip();
 await page.locator('#music-volume').focus();await page.keyboard.press('End');
 await game.waitForFunction(()=>__office.state.office.audio.musicVolume===1);
 const music=await readFile('frontend/sounds/office/chill.mp3');
 const upload=await page.request.post(origin+'/api/music',{headers:{Origin:origin,'Content-Type':'audio/mpeg','X-Track-Name':encodeURIComponent('Bài thử.mp3')},data:music});
 assert.equal(upload.status(),201);
 const id=(await upload.json()).id;
 await page.selectOption('#music-list',{value:id});
 await game.waitForFunction(id=>__office.audio.music.src.endsWith('/api/music/'+id),id);
 const remove=await page.request.post(origin+'/api/music-remove',{headers:{Origin:origin},data:{id}});
 assert.equal(remove.status(),200);
 await game.waitForFunction(()=>__office.state.office.audio.trackId===null);
 await page.request.post(origin+'/api/mode',{headers:{Origin:origin},data:{mode:'LIVE'}});
 assert.equal((await page.request.post(origin+'/api/demo',{headers:{Origin:origin},data:{type:'gift',giftName:'Rose'}})).status(),409);
 await page.request.post(origin+'/api/mode',{headers:{Origin:origin},data:{mode:'DEMO'}});
 await game.setViewportSize({width:1280,height:720});
 await game.click('#fullscreen');
 await game.waitForFunction(()=>document.fullscreenElement===document.body);
 const bounds=await game.locator('#frame').boundingBox();
 assert.ok(Math.abs(bounds.width/bounds.height-9/16)<.01);
 assert.ok(bounds.height<=720.1);
 assert.deepEqual(errors,[]);
 await game.close();
 await page.route('**/api/state',route=>route.fulfill({status:404,body:''}));
 await page.goto(origin+'/admin');
 const staticGame=await context.newPage();
 await staticGame.route('**/api/state',route=>route.fulfill({status:404,body:''}));
 await staticGame.goto(origin+'/');
 await staticGame.waitForFunction(()=>__office?.state?.mode==='DEMO');
 await page.locator('[data-gift="claimSecretary"]').click();
 await staticGame.waitForFunction(()=>__office.state.office.secretary.id!==null);
 await staticGame.close();
 console.log('Verified office gifts, names, recorded speech, scene queue, bedroom interrupt, firing/refill, audio upload/volume, LIVE isolation, Pages DEMO and fullscreen.');
} finally {
 await browser?.close();
 await app.close();
}
